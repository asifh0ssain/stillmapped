"""Discovery, record assembly, output and the oracle.

run() is the same code online (fetch) and offline (build): online it fills
the snapshot, offline it reads only what the snapshot's manifest hashes.
"""

import json
import os
import re

from stillmapped.resolve import validate_record

from . import feeds

MODULES = ("openssl", "php")
NOTE = ("Generated by tools/sync from the snapshot taken on {date}. Every record comes from one "
        "primary vendor feed; any doubt gives no record, so the scanner answers unknown.")


class Out:
    def __init__(self, date):
        self.date, self.records, self.skips, self.dups = date, {}, set(), set()

    def skip(self, cve, distro, stream, package, reason):
        self.skips.add((cve, distro, stream, package, reason))

    def add(self, cve, module, rec):
        rec = {**rec, **({"file": feeds.FILE[module]} if module in feeds.FILE else {}), "checked": self.date}
        key = (rec["vendor"], rec["stream"], rec["package"], rec["branch"])
        problems = validate_record({**rec, "cve": cve, "module": module})
        if problems:
            return self.skip(cve, *key[:3], "validator: " + "; ".join(problems))
        recs, old = self.records.setdefault((cve, module), {}), self.records.get((cve, module), {}).get(key)
        if old or (cve, key) in self.dups:
            # Owner's rule: two fix versions for one build give the highest;
            # anything that does not compare cleanly gives no record.
            same = old and old["status"] == rec["status"] == "fixed" and old["match"] == rec["match"]
            top = same and feeds.highest(rec["match"], [old["fixed"], rec["fixed"]])
            if not top:
                self.dups.add((cve, key))
                recs.pop(key, None)
                return self.skip(cve, *key[:3], f"two records for branch {key[3]} that do not compare cleanly")
            rec = rec if rec["fixed"] == top else old
        recs[key] = rec


def discover(snap, year, index, php):
    """{CVE: module} from the per-package views of Debian, Ubuntu and php.net,
    CVE ids from year - 3 on. A CVE seen under both modules is left out."""
    found = {}
    for module, streams in feeds.DEB_SRC.items():
        for src in sorted(set(streams.values())):
            page = snap.get(f"https://security-tracker.debian.org/tracker/source-package/{src}") or b""
            found.update({c: found.get(c, set()) | {module} for c in re.findall(r"/tracker/(CVE-\d{4}-\d+)\"", page.decode())})
        for vulns in index[module].values():
            for v in vulns or []:
                found.update({c: found.get(c, set()) | {module} for c in v.get("upstream", []) if v["id"] == f"UBUNTU-{c}"})
    for t in [t for _, t in php["sections"]] + [t for _, _, t in php["news"]]:
        found.update({c: found.get(c, set()) | {"php"} for c in re.findall(r"CVE-\d{4}-\d+", t)})
    return {c: m.pop() if len(m) == 1 else None for c, m in found.items() if int(c.split("-")[1]) >= year - 3}


def run(snap):
    year, out = int(snap.date[:4]), Out(snap.date)
    index = {m: feeds.ubuntu_index(snap, m) for m in MODULES}
    php = feeds.phpnet(snap, year)
    for cve, module in sorted(discover(snap, year, index, php).items()):
        if module is None:
            out.skip(cve, "*", "*", "*", "listed under both PHP and OpenSSL")
            continue
        eol = php["eol"] if module == "php" else {}
        feeds.debian(snap, cve, module, out, eol)
        feeds.ubuntu(snap, index[module], cve, module, out)
        feeds.rhel(snap, cve, module, out, eol)
        feeds.sles(snap, cve, module, out, eol)
        if module == "php":
            feeds.upstream(php, cve, out)
    return out


def write(out, path):
    """One data file per CVE in the scanner's format, plus skipped.tsv. Sorted
    keys and records, so the same snapshot gives the same bytes."""
    os.makedirs(path, exist_ok=True)
    for (cve, module), recs in sorted(out.records.items()):
        if recs:
            doc = {"name": cve, "module": module, "cves": [cve], "note": NOTE.format(date=out.date),
                   "records": [recs[k] for k in sorted(recs)]}
            with open(os.path.join(path, f"{cve}.json"), "w") as fh:
                fh.write(json.dumps(doc, indent=1, sort_keys=True) + "\n")
    with open(os.path.join(path, "skipped.tsv"), "w") as fh:
        fh.write("cve\tdistro\tstream\tpackage\treason\n")
        fh.writelines("\t".join(s) + "\n" for s in sorted(out.skips))


def oracle(path, hand):
    """(differences, extras) between the generated files and the hand-checked
    data file. Every hand record must be generated with every field equal
    except checked and evidence (owner's answer 1); extras are records the
    hand file never had. The hand file is one advisory for several CVEs, so its
    evidence_url is compared as the record's own CVE page (owner, 2026-10-30)."""
    with open(hand) as fh:
        doc = json.load(fh)
    diffs, extras = [], []
    for cve in doc["cves"]:
        try:
            with open(os.path.join(path, f"{cve}.json")) as fh:
                gen = {(r["vendor"], r["stream"], r["package"], r["branch"]): r for r in json.load(fh)["records"]}
        except FileNotFoundError:
            gen = {}
        for r in doc["records"]:
            key = (r["vendor"], r["stream"], r["package"], r["branch"])
            want = {k: v for k, v in r.items() if k not in ("checked", "evidence")}
            want["evidence_url"] = re.sub("|".join(doc["cves"]), cve, want["evidence_url"])
            got = {k: v for k, v in gen.pop(key, {}).items() if k not in ("checked", "evidence")}
            if want != got:
                diffs.append(f"{cve} {key}: hand {want} != generated {got or 'none'}")
        extras += [f"{cve} {k}: {gen[k]['fixed'] if 'fixed' in gen[k] else gen[k]['status']}" for k in sorted(gen)]
    return diffs, extras
